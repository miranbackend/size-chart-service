def test_check_results_for_each_outcome(conn, http):
    add_product(conn, 21, "https://store.example.com/products/captcha")
    add_product(conn, 22, "https://store.example.com/products/sizes-only")
    add_product(conn, 23, "https://store.example.com/products/image-chart")
    add_product(conn, 24, "https://down.example.com/products/x")
    add_product(conn, 25, "https://store.example.com/products/missing")
    add_product(conn, 26, "https://store.example.com/products/kurta", active=False)

    assert worker.process_once() == 5          # inactive product is never picked

    assert check(conn, 21) == "blocked"
    assert check(conn, 22) == "not_found"
    assert check(conn, 23) == "pending_ocr"
    assert check(conn, 24) == "failed"
    assert check(conn, 25) == "not_found"      # 404
    assert check(conn, 26) is None
    assert conn.execute("SELECT count(*) AS n FROM product_size_charts").fetchone()["n"] == 0

    # Nothing is due again yet.
    assert worker.process_once() == 0


def test_due_products_are_rechecked(conn, http):
    add_product(conn, 31, "https://down.example.com/products/x")
    add_product(conn, 32, "https://store.example.com/products/sizes-only")
    add_product(conn, 33, "https://store.example.com/products/kurta")
    conn.execute("""
        INSERT INTO product_size_chart_checks (product_id, result, checked_at) VALUES
            (31, 'failed',     NOW() - interval '7 hours'),
            (32, 'not_found',  NOW() - interval '2 days'),
            (33, 'processing', NOW() - interval '1 hour')
    """)
    # failed after 6h and stale 'processing' after 30m are due; not_found waits 30 days.
    claimed = {p["product_id"] for p in worker.claim_products(10)}
    assert claimed == {31, 33}


def test_unexpected_extraction_error_marks_failed(conn, http, monkeypatch):
    add_product(conn, 41, "https://store.example.com/products/kurta")

    def explode(*a, **k):
        raise RuntimeError("parser exploded")

    monkeypatch.setattr(worker, "extract_product", explode)
    assert worker.process_once() == 1
    assert check(conn, 41) == "failed"
    assert chart_row(conn, 41) is None


def test_release_returns_unprocessed_products(conn, http):
    add_product(conn, 51, "https://store.example.com/products/kurta")
    products = worker.claim_products(10)
    assert check(conn, 51) == "processing"
    worker.release_products(products)
    assert check(conn, 51) is None
    assert {p["product_id"] for p in worker.claim_products(10)} == {51}


def test_claim_never_hands_the_same_product_to_two_workers(conn, http):
    for pid in range(60, 70):
        add_product(conn, pid, "https://store.example.com/products/kurta")
    first = {p["product_id"] for p in worker.claim_products(4)}
    second = {p["product_id"] for p in worker.claim_products(4)}
    assert len(first) == len(second) == 4
    assert not first & second
