def _chart(sizes):
    return Chart(sizes=sizes, unit="inch", method="html_table", source="other", confidence=0.75)


def test_chart_upsert_is_idempotent(conn):
    add_product(conn, 1, "https://store.example.com/products/x")
    chart = _chart({"S": {"chest": "38"}, "M": {"chest": "40"}, "L": {"chest": "42"}})
    for _ in range(2):
        with worker.get_pool().connection() as c, c.transaction():
            worker.save_chart(c, 1, chart, "https://store.example.com/products/x")

    updated = _chart({"S": {"chest": "38.5"}, "M": {"chest": "40.5"}})
    with worker.get_pool().connection() as c, c.transaction():
        worker.save_chart(c, 1, updated, "https://store.example.com/products/x")

    rows = conn.execute("SELECT * FROM product_size_charts").fetchall()
    assert len(rows) == 1                                   # one row per product
    assert rows[0]["chart"]["sizes"] == {"S": {"chest": "38.5"}, "M": {"chest": "40.5"}}
    assert rows[0]["chart"]["size_order"] == ["S", "M"]
    assert rows[0]["updated_at"] >= rows[0]["created_at"]


def test_save_chart_refuses_single_row(conn):
    add_product(conn, 2, "https://store.example.com/products/x")
    with pytest.raises(ValueError):
        with worker.get_pool().connection() as c, c.transaction():
            worker.save_chart(c, 2, _chart({"M": {"chest": "40"}}), "https://x")
    assert chart_row(conn, 2) is None


