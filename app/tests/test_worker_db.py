def add_product(conn, pid, url, title="Linen Kurta", shopify_id=SHOPIFY_ID, active=True):
    conn.execute(
        "INSERT INTO products (id, shopify_product_id, title, product_url, is_active) "
        "VALUES (%s, %s, %s, %s, %s)",
        (pid, shopify_id, title, url, active),
    )


def check(conn, pid):
    row = conn.execute("SELECT result FROM product_size_chart_checks WHERE product_id = %s",
                       (pid,)).fetchone()
    return row and row["result"]


def chart_row(conn, pid):
    return conn.execute("SELECT * FROM product_size_charts WHERE product_id = %s", (pid,)).fetchone()


