def test_batch_runs_products_concurrently(conn, http, monkeypatch):
    import time
    monkeypatch.setattr(worker.SETTINGS, "concurrency", 8)
    worker._executor = None
    for pid in range(200, 208):
        add_product(conn, pid, f"https://store{pid}.example.com/products/shopify-chart")
    slow = worker.fetch_http

    def delayed(client, url):
        time.sleep(0.3)
        return slow(client, url)

    monkeypatch.setattr(worker, "fetch_http", delayed)
    start = time.monotonic()
    assert worker.process_once() == 8
    elapsed = time.monotonic() - start
    # 8 products x (robots + .js) x 0.3 s = 4.8 s one by one; in parallel ~0.6 s
    assert elapsed < 2.5, elapsed
    assert {check(conn, pid) for pid in range(200, 208)} == {"found"}


def test_batch_takes_one_product_per_store(conn, http):
    # Real case (babyhug.in): a big store filled whole batches and its products
    # queued behind each other's per-store pacing.
    for pid in range(300, 320):
        add_product(conn, pid, f"https://big.example.com/products/p{pid}", store_id=1)
    for pid in range(320, 325):
        add_product(conn, pid, f"https://small{pid}.example.com/products/p", store_id=pid)
    batch = worker.claim_products(8)
    stores = [p["product_url"].split("/")[2] for p in batch]
    assert len(stores) == len(set(stores)) == 6      # 5 small stores + 1 from the big store


def test_http_429_is_rate_limited_and_retried_within_the_hour(conn, http):
    add_product(conn, 400, "https://throttled.example.com/products/kurta")
    worker.process_once()
    assert check(conn, 400) == "rate_limited"
    assert worker.get_limiter().rate < 10_000            # limiter slowed down
